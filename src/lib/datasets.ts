export type ColumnKind =
  | "text"
  | "address"
  | "tx"
  | "amount"
  | "count"
  | "date"
  | "status"
  | "boolean"
  | "proposalMode";
export type DatasetColumn = {
  key: string;
  label: string;
  kind: ColumnKind;
  select: string;
};
